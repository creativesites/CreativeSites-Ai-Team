// Compiles the stand-up report and its markdown copy (WP6 6.3 e). Pure: no store access, no clock.
// Rules: recorded facts and agent-reported text are kept apart and labelled; an agent that did not
// reply has no reported text at all; claims that no record backs are listed as discrepancies.

import { emptyFacts, type AgentFacts, type GatheredFacts } from './facts.ts';
import type { AgentEntry, StandupReply } from './replies.ts';

export type AgentStatus = 'reported' | 'no_update' | 'absent';

export interface ReportAgent {
  agentId: string;
  name: string;
  status: AgentStatus;
  /** Why the agent is absent; null otherwise. */
  reason: string | null;
  /** Recorded in the store: authoritative. */
  facts: AgentFacts;
  /** What the agent said, unverified. Null unless the agent actually replied. */
  reported: (StandupReply & { label: 'agent-reported (unverified)' }) | null;
  discrepancies: string[];
}

export interface StandupReport {
  date: string;
  since: string;
  generatedAt: string;
  teamId: string;
  agents: ReportAgent[];
  teamFacts: AgentFacts;
  summary: { reported: number; noUpdate: number; absent: number; discrepancies: number; blockersReported: number };
}

export interface CompileInput {
  date: string;
  generatedAt: string;
  teamId: string;
  facts: GatheredFacts;
  roster: { id: string; name: string }[];
  entries: AgentEntry[];
  replies: Map<string, StandupReply>;
}

const TASK_ID = /\b(?:task|tsk)_[0-9a-f]{8,}\b/g;

export function findDiscrepancies(reply: StandupReply, facts: AgentFacts, allCompletedTaskIds: Set<string>, since: string): string[] {
  const out: string[] = [];
  if (!reply.done) return out;
  const mentioned = [...new Set(reply.done.match(TASK_ID) ?? [])];
  for (const id of mentioned) {
    if (!allCompletedTaskIds.has(id)) out.push(`Claims ${id} is done, but no task.done or task.verified record exists for it since ${since}.`);
  }
  const hasRecord = facts.tasksCompleted.length > 0 || facts.evidence.length > 0 || facts.jobStageChanges.length > 0;
  if (!mentioned.length && !hasRecord) {
    out.push(`Reports work done, but no task completion, evidence or job change is recorded for this agent since ${since}.`);
  }
  return out;
}

export function compileReport(input: CompileInput): StandupReport {
  const completedIds = new Set(input.facts.all.tasksCompleted.map((t) => t.taskId));
  const agents: ReportAgent[] = input.roster.map((who) => {
    const entry = input.entries.find((e) => e.agentId === who.id);
    const facts = input.facts.byActor[who.id] ?? emptyFacts();
    const reply = input.replies.get(who.id);
    if (!entry || entry.state === 'absent') {
      return { agentId: who.id, name: who.name, status: 'absent', reason: entry?.reason ?? 'not part of this stand-up', facts, reported: null, discrepancies: [] };
    }
    if (!reply) {
      return { agentId: who.id, name: who.name, status: 'no_update', reason: null, facts, reported: null, discrepancies: [] };
    }
    return {
      agentId: who.id,
      name: who.name,
      status: 'reported',
      reason: null,
      facts,
      reported: { ...reply, label: 'agent-reported (unverified)' },
      discrepancies: findDiscrepancies(reply, facts, completedIds, input.facts.since),
    };
  });
  return {
    date: input.date,
    since: input.facts.since,
    generatedAt: input.generatedAt,
    teamId: input.teamId,
    agents,
    teamFacts: input.facts.all,
    summary: {
      reported: agents.filter((a) => a.status === 'reported').length,
      noUpdate: agents.filter((a) => a.status === 'no_update').length,
      absent: agents.filter((a) => a.status === 'absent').length,
      discrepancies: agents.reduce((n, a) => n + a.discrepancies.length, 0),
      blockersReported: agents.reduce((n, a) => n + (a.reported?.blockers.length ?? 0), 0),
    },
  };
}

const bullets = (items: string[], empty = '_none recorded_'): string => (items.length ? items.map((i) => `- ${i}`).join('\n') : empty);

function factLines(f: AgentFacts): string[] {
  return [
    ...f.tasksCompleted.map((t) => `Task ${t.status}: ${t.title} (${t.taskId})`),
    ...f.evidence.map((e) => `Evidence ${e.class} ${e.kind}: ${e.summary}`),
    ...f.blockersOpened.map((b) => `Blocker opened: ${b.summary}`),
    ...f.blockersResolved.map((b) => `Blocker resolved: ${b.summary}`),
    ...f.jobStageChanges.map((j) => `Job ${j.jobId} stage ${j.from ?? '?'} to ${j.to ?? '?'}`),
    ...f.sessionsFailed.map((s) => `Session failed: ${s.sessionId}${s.error ? ` (${s.error.slice(0, 120)})` : ''}`),
  ];
}

export function renderMarkdown(r: StandupReport): string {
  const s = r.summary;
  const lines = [
    `# Daily stand-up ${r.date}`,
    '',
    `Window: ${r.since} to ${r.generatedAt}. Generated by the MyaOS runtime.`,
    `Reported ${s.reported}, no update ${s.noUpdate}, absent ${s.absent}; ${s.discrepancies} discrepancies; ${s.blockersReported} blockers reported.`,
    '',
    'Recorded facts come from the runtime store. Text marked "agent-reported" is what the agent said and has not been verified.',
    '',
  ];
  for (const a of r.agents) {
    lines.push(`## ${a.name} (${a.agentId}): ${a.status.replace('_', ' ')}`);
    if (a.status === 'absent') lines.push(`Absent: ${a.reason ?? 'offline'}.`);
    if (a.status === 'no_update') lines.push('No reply was received before the deadline.');
    lines.push('', '**Recorded**', bullets(factLines(a.facts)));
    if (a.reported) {
      lines.push('', '**Agent-reported (unverified)**', `- Done: ${a.reported.done || '_not stated_'}`, `- Next: ${a.reported.next || '_not stated_'}`);
      lines.push(`- Blockers: ${a.reported.blockers.length ? a.reported.blockers.join('; ') : 'none'}`);
    }
    if (a.discrepancies.length) lines.push('', '**Discrepancies**', bullets(a.discrepancies));
    lines.push('');
  }
  lines.push('## Team facts', bullets(factLines(r.teamFacts)), '');
  return lines.join('\n');
}
